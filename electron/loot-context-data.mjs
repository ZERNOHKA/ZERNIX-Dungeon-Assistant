/**
 * Карта биома UI → ключ ситуаций (с примесями «особняк» и «лаборатория»).
 * @param {string} environment
 * @param {() => number} rng
 */
export function resolveSituationBucket(environment, rng) {
  const e = String(environment || "any").toLowerCase();
  const keys = ["Urban", "Dungeon", "Wilderness", "NobleEstate", "Laboratory"];
  if (e === "urban") {
    return rng() < 0.38 ? "NobleEstate" : "Urban";
  }
  if (e === "dungeon" || e === "cave") {
    return rng() < 0.2 ? "Laboratory" : "Dungeon";
  }
  if (e === "forest" || e === "swamp" || e === "coastal" || e === "mountain" || e === "arctic") {
    return "Wilderness";
  }
  if (e === "any") {
    return keys[Math.floor(rng() * keys.length)];
  }
  return "Wilderness";
}

/**
 * @param {keyof typeof LOOT_SITUATIONS} bucket
 * @param {() => number} rng
 */
export function pickSituation(bucket, rng) {
  const list = LOOT_SITUATIONS[bucket];
  if (!list || list.length === 0) {
    return LOOT_SITUATIONS.Wilderness[Math.floor(rng() * 50)];
  }
  return list[Math.floor(rng() * list.length)];
}

