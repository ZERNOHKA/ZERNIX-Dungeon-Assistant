function buildFifty(lead, tail, flavor, salt) {
  /** @type {LootSituation[]} */
  const out = [];
  const tn = tail.length;
  const fn = flavor.length;
  for (let i = 0; i < 50; i += 1) {
    out.push({
      location: `${lead[i % lead.length]}, ${tail[(i * 7 + salt) % tn]}`,
      difficulty: spreadDc(i, salt + 3),
      skill: LOOT_SKILL_CYCLE[i % 5],
      flavor: flavor[(i * 11 + salt * 5) % fn],
    });
  }
  return out;
}

