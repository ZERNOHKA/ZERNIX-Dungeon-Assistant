/**
 * @param {() => number} rng
 * @param {boolean} [isMagic]
 * @param {'curse'|'blessing'|'quirk'|null} [twistKind]
 */
export function pickSensoryDetail(rng, isMagic = false, twistKind = null) {
  if (twistKind === "curse") {
    const line = SENSORY_CURSE_HINTS[Math.floor(rng() * SENSORY_CURSE_HINTS.length)];
    if (isMagic && rng() < 0.5) {
      const extra = SENSORY_MAGIC_EXTRA[Math.floor(rng() * SENSORY_MAGIC_EXTRA.length)];
      return `${line} ${extra}`;
    }
    return line;
  }
  const roll = rng();
  let line;
  if (roll < 0.34) {
    line = SENSORY_SOUND[Math.floor(rng() * SENSORY_SOUND.length)];
  } else if (roll < 0.67) {
    line = SENSORY_TEMPERATURE[Math.floor(rng() * SENSORY_TEMPERATURE.length)];
  } else {
    line = SENSORY_SMELL[Math.floor(rng() * SENSORY_SMELL.length)];
  }
  if (isMagic && rng() < 0.55) {
    const extra = SENSORY_MAGIC_EXTRA[Math.floor(rng() * SENSORY_MAGIC_EXTRA.length)];
    return `${line} ${extra}`;
  }
  return line;
}

