/** Умножает числовые суммы вида «12 зм», «50 см» в строке прейскуранта (ориентир для Мастера). */
export function scalePriceLine(priceStr, factor) {
  if (factor === 1) return priceStr;
  return priceStr.replace(/(\d+)\s*(зм|см)\b/gi, (_, digits, unit) => {
    const n = Number.parseInt(digits, 10);
    const scaled =
      factor < 1 ? Math.max(1, Math.round(n * factor)) : Math.round(n * factor);
    return `${scaled} ${unit}`;
  });
}

function tieredServices(baseServices, tier) {
  const f = tier.priceFactor;
  return baseServices.map((s) => {
    let priceGp = scalePriceLine(s.priceGp, f);
    if (tier.id === 'apprentice') {
      priceGp = `${priceGp} _(подмастерье: дешевле ~на 30%; магические вещи может испортить)_`;
    } else if (tier.id === 'expert') {
      priceGp = `${priceGp} _(грандмастер: ×5 к суммам зм/см; редкие артефакты; возможен условный +1 к прочности)_`;
    } else if (tier.id === 'legendary') {
      priceGp = `${priceGp} _(легендарный мастер: ×12; снятие проклятия / восстановление разрушенного — по сюжету)_`;
    }
    return { work: s.work, priceGp };
  });
}

/** Извлекает суммы зм и см из строки прейскуранта (после scalePriceLine / tier). */
export function extractCoinsFromPriceLine(priceStr) {
  const s = String(priceStr ?? '');
  let zm = 0;
  let sm = 0;
  for (const m of s.matchAll(/(\d+)\s*зм\b/giu)) {
    zm += Number.parseInt(m[1], 10);
  }
  for (const m of s.matchAll(/(\d+)\s*см\b/giu)) {
    sm += Number.parseInt(m[1], 10);
  }
  return { zm, sm };
}

/** Числовые поля по каждой услуге + сумма для UI (золотой блок в интерфейсе). */
export function enrichServicesPricing(services) {
  let totalZm = 0;
  let totalSm = 0;
  const servicesEnriched = services.map((svc) => {
    const { zm, sm } = extractCoinsFromPriceLine(svc.priceGp);
    totalZm += zm;
    totalSm += sm;
    return {
      ...svc,
      coinsZmInLine: zm,
      coinsSmInLine: sm,
    };
  });
  return {
    services: servicesEnriched,
    pricingRollup: {
      totalZm,
      totalSm,
      /** Алиас для UI: сумма всех явных зм в строках услуг. */
      totalCostZm: totalZm,
      noteRu:
        'Сумма всех явных чисел зм/см в строках услуг после уровня мастера (ориентир; строки без чисел не входят).',
    },
  };
}

