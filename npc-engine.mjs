export function resolveProfessionCategory(prof) {
  if (prof.category) return prof.category;
  if (prof.utility === 'information' || prof.utility === 'magic') return 'intellect';
  if (prof.utility === 'combat') return 'services';
  if (prof.utility === 'trade') return 'craft';
  return 'services';
}

export function getProfessionLabel(prof, female) {
  if (prof.labelM && prof.labelF) return female ? prof.labelF : prof.labelM;
  return prof.nameRu;
}

function pickCoreSpecialization(prof) {
  const pool = CORE_SPECIALIZATION_POOLS[prof.id];
  if (pool?.length) return pick(pool);
  const byUtility = {
    trade: ['сезонные дефициты и тайные склады', 'работа без лишних свидетелей на табличке'],
    information: ['доступ к регистрам и подлинность печати', 'слухи с ценником за строку'],
    combat: ['полевой ремонт без героических речей', 'услуги, где кровь — часть калькуляции'],
    magic: ['компоненты без печати культа', 'обряд как атмосфера — не как гарантия'],
  };
  return pick(byUtility[prof.utility] || ['узкая ниша под конкретный заказ']);
}

export function formatSpecializationLine(prof, female) {
  const role = getProfessionLabel(prof, female);
  const spec = prof.specializationPool?.length ? pick(prof.specializationPool) : pickCoreSpecialization(prof);
  const titled = role.charAt(0).toUpperCase() + role.slice(1);
  return `${titled}: ${spec}`;
}

function pickCraftsmanshipNarrativeHook(tierId) {
  const pool = CRAFTSMANSHIP_NARRATIVE_HOOKS[tierId] || CRAFTSMANSHIP_NARRATIVE_HOOKS.journeyman;
  return pick(pool);
}

/**
 * Оценка цены ремонта по типу предмета, потере целостности и уровню мастера NPC.
 * @param {'weapon'|'armor'|'tool'|'gear'|'magic_item'|'artifact'} itemType
 * @param {number} integrityLoss — доля от 0 до 1 (сколько «сломано»)
 * @param {string} npcTierId — id из PROFESSION_TIERS
 */
export function calculateServicePrice(itemType, integrityLoss, npcTierId) {
  const loss = Math.min(1, Math.max(0, Number(integrityLoss)));
  const tier =
    PROFESSION_TIERS.find((t) => t.id === npcTierId) ?? PROFESSION_TIERS.find((t) => t.id === 'journeyman');
  const mult =
    {
      weapon: 1,
      armor: 1.25,
      tool: 0.75,
      gear: 0.9,
      magic_item: 2.8,
      artifact: 5,
    }[itemType] ?? 1;
  const raw = 3 + Math.round(loss * 48 * mult * tier.priceFactor);
  const priceZm = Math.max(1, raw);
  const tierCue =
    tier.id === 'apprentice'
      ? 'Подмастерье: обыденный ремонт дешевле; магическая вещь может выйти из мастерской хуже, чем вошла.'
      : tier.id === 'journeyman'
        ? 'Мастер: стабильная работа и базовая магия без сюрпризов.'
        : tier.id === 'expert'
          ? 'Грандмастер: редкие артефакты и условный бонус к прочности — если Мастер сочтёт нужным.'
          : 'Легендарный мастер: снятие проклятия или восстановление разрушенного — отдельный договор и цена вне таблицы.';
  return {
    itemType,
    integrityLoss: loss,
    npcTierId: tier.id,
    npcTierNameRu: tier.nameRu,
    priceZm,
    explanationRu: tierCue,
    summaryRu: `Ориентир ремонта: **${priceZm} зм** (${tier.nameRu}), тип «${itemType}», потеря целостности ~${Math.round(loss * 100)}%. ${tierCue}`,
  };
}

