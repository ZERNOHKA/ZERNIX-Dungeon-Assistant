function raceArrivalPhrase(raceId, fem) {
  const pool = ARRIVAL_SNIPPETS[raceId] ?? ARRIVAL_SNIPPETS.human;
  return pick(fem ? pool.female : pool.male);
}

function buildBackstory(firstName, professionLabelRu, secret, disposition, gender, race, socialStake) {
  const fem = gender.id === 'female';
  const pronoun = fem ? 'она' : 'он';
  const pronounPoss = fem ? 'её' : 'его';
  const verbCame = fem ? 'прибыла' : 'прибыл';
  const busy = fem ? 'занята' : 'занят';
  const raceAdj = race.nameRu.toLowerCase();
  const arrival = raceArrivalPhrase(race.id, fem);
  const modStr = `${disposition.modifier >= 0 ? '+' : ''}${disposition.modifier}`;
  const stakeLine = socialStake.explanation;
  const dispositionText = dispositionLabel(disposition, gender);

  const templates = [
    () =>
      `${firstName} — ${raceAdj}, по профессии ${professionLabelRu}; ${pronoun} ${verbCame} сюда, чтобы выдохнуть от собственного прошлого, но роль «${socialStake.roleLabel}» не отпускает: ${stakeLine} Когда в разговоре всплывает «${secret}», ${pronoun} ${busy} телом и голосом осторожнее обычного, а к незнакомцам настроен${fem ? 'а' : ''} так: «${dispositionText}» (${modStr}).`,
    () =>
      `История ${firstName} начинается не с легенды, а с работы рук: ${professionLabelRu} среди ${raceAdj} — ремесло, которое кормит и калечит одновременно. Статус «${socialStake.roleLabel}» висит над ${pronounPoss} головой осязаемо: ${stakeLine} Тайна «${secret}» звучит в каждом шорохе бумаги и в каждом чужом взгляде; отношение к героям — «${dispositionText}» (${modStr}).`,
    () =>
      `${firstName} держится за город как за спасательный круг: ${arrival} При этом «${socialStake.roleLabel}» заставляет нервничать там, где другие просто торгуются — ${stakeLine} Плечом к плечу с этим идёт «${secret}» — короткая правда, которую ${pronoun} предпочёл${fem ? 'а' : ''} бы не произносить вслух; ${pronoun} придерживается линии «${dispositionText}» (${modStr}).`,
    () =>
      `Если спросить ${firstName} открыто, ${pronoun} назовёт себя ${professionLabelRu} и нахмурится: роль «${socialStake.roleLabel}» для ${pronounPoss} не театр, а быт — ${stakeLine} На фоне этого «${secret}» выглядит то насмешкой судьбы, то предупреждением; разговор с героями складывается как «${dispositionText}» (${modStr}).`,
    () =>
      `${firstName} ${fem ? 'училась' : 'учился'} верить в инструмент и в слово — так устроены ${raceAdj}. Но социальная позиция «${socialStake.roleLabel}» подрывает равновесие сильнее любого кризиса: ${stakeLine} Когда речь заходит о «${secret}», ${pronoun} будто снова стоит на краю дороги с неоплаченным проездом; душа отвечает посетителям через «${dispositionText}» (${modStr}).`,
    () =>
      `Город знает ${firstName} как ${professionLabelRu}, а про ${pronounPoss} ${raceAdj} происхождение шепчутся отдельно — так сложилось. Между тем «${socialStake.roleLabel}» делает каждую встречу с героями испытанием: ${stakeLine} Секрет «${secret}» лежит на столе, как нож лезвием вверх; характер встречи — «${dispositionText}» (${modStr}).`,
  ];
  return pick(templates)();
}

function pickGreetingPhrase(moodKey) {
  const key = GREETING_MOODS.includes(moodKey) ? moodKey : 'нейтральное';
  const list = GREETING_PHRASES[key] || GREETING_PHRASES.нейтральное;
  return pick(list);
}

/**
 * Генерация NPC.
 * @param {object} [options]
 * @param {string} [options.raceId]
 * @param {string} [options.genderId] — female | male
 * @param {string} [options.greetingMood] — см. GREETING_MOODS
 * @param {string} [options.professionId]
 */
export function generateNPC(options = {}) {
  const race = options.raceId
    ? RACES.find((r) => r.id === options.raceId) || pick(RACES)
    : pick(RACES);

  const gender = options.genderId
    ? GENDERS.find((g) => g.id === options.genderId) || pick(GENDERS)
    : pick(GENDERS);

  const nameFirst = pickRaceFirstName(race.id, gender.id === 'female');
  const nameFull = `${nameFirst} ${pick(SURNAMES)}`;

  const profession = options.professionId
    ? PROFESSIONS.find((p) => p.id === options.professionId) || pick(PROFESSIONS)
    : pick(PROFESSIONS);

  const female = gender.id === 'female';
  const professionLabelRu = getProfessionLabel(profession, female);
  const professionCategory = resolveProfessionCategory(profession);
  const specializationLine = formatSpecializationLine(profession, female);
  const hobbyEclectic = pick(HOBBIES_ECLECTIC);
  const whereToFindNow = pick(WHERE_FIND_NOW);

  const utility = UTILITIES.find((u) => u.id === profession.utility) || UTILITIES[0];
  const disposition = pick(DISPOSITIONS);

  const manner = pick(MANNERS);
  const secret = pick(SECRETS_AND_HOOKS);
  const pocketItems = pickMany(POCKET_ITEMS, randInt(1, 3));
  const socialStake = pickSocialStake();
  const professionTier = pickProfessionTier();
  const servicesTiered = tieredServices(profession.services, professionTier);
  const { services: servicesEnriched, pricingRollup } = enrichServicesPricing(servicesTiered);

  const craftsmanshipNarrativeHook = pickCraftsmanshipNarrativeHook(professionTier.id);
  const repairPricingWeaponSample = calculateServicePrice('weapon', 0.35, professionTier.id);
  const repairPricingMagicSample = calculateServicePrice('magic_item', 0.6, professionTier.id);

  const greetingMood =
    options.greetingMood && GREETING_MOODS.includes(options.greetingMood)
      ? options.greetingMood
      : pick(GREETING_MOODS);
  const greeting = pickGreetingPhrase(greetingMood);

  const appearance = buildAppearance(gender, race);
  const backstory = buildBackstory(nameFirst, professionLabelRu, secret, disposition, gender, race, socialStake);

  const data = {
    meta: {
      system: 'D&D 5.5 Player\'s Handbook 2024 (ориентир)',
      generatedAt: new Date().toISOString(),
    },
    identity: {
      name: nameFull,
      firstName: nameFirst,
      gender: gender.nameRu,
      pronoun: gender.pronounRu,
      race: race.nameRu,
      raceLifespan: race.lifespanRu,
      raceVisualTraits: race.visualTraits,
      raceNotes: race.notes,
    },
    role: {
      profession: profession.nameRu,
      professionLabelRu,
      professionCategory,
      professionCategoryLabelRu: CATEGORY_LABEL_RU[professionCategory] ?? professionCategory,
      specialization: specializationLine,
      professionTier: professionTier.nameRu,
      professionTierId: professionTier.id,
      professionTierQuality: professionTier.qualityRu,
      craftingTier: {
        id: professionTier.id,
        nameRu: professionTier.nameRu,
        craftingRu: professionTier.craftingRu,
        englishKey:
          professionTier.id === 'apprentice'
            ? 'Apprentice'
            : professionTier.id === 'journeyman'
              ? 'Journeyman'
              : professionTier.id === 'expert'
                ? 'Expert'
                : 'Legendary',
      },
      utility: {
        id: utility.id,
        name: utility.nameRu,
        description: utility.desc,
      },
      services: servicesEnriched,
      pricingRollup,
      repairPricing: {
        sampleWeapon: repairPricingWeaponSample,
        sampleMagicItem: repairPricingMagicSample,
      },
    },
    portrayal: {
      appearance,
      manner,
      greetingMood,
      greetingFirstPhrase: greeting,
      hobbyEclectic,
      whereToFindNow,
      craftsmanshipNarrativeHook,
      disposition: {
        id: disposition.id,
        label: dispositionLabel(disposition, gender),
        modifier: disposition.modifier,
      },
    },
    plot: {
      secretOrHook: secret,
      pockets: pocketItems,
      socialStake,
    },
    narrative: {
      backstoryParagraph: backstory,
    },
  };

  return {
    data,
    markdown: formatNPCMarkdown(data),
    toString() {
      return this.markdown;
    },
  };
}

function formatNPCMarkdown(d) {
  const lines = [];
  lines.push(`## ${d.identity.name}`);
  lines.push('');
  lines.push(`**Раса:** ${d.identity.race}`);
  lines.push(`**Срок жизни (типичный):** ${d.identity.raceLifespan}`);
  lines.push(`**Ключевые визуальные черты:** ${d.identity.raceVisualTraits}`);
  lines.push(`_Заметка:_ ${d.identity.raceNotes}`);
  lines.push('');
  lines.push(`**Пол:** ${d.identity.gender} (${d.identity.pronoun})`);
  lines.push(`**Роль:** ${d.role.profession}`);
  if (d.role.professionLabelRu) {
    lines.push(`**Подпись профессии (род):** ${d.role.professionLabelRu}`);
  }
  if (d.role.professionCategoryLabelRu) {
    lines.push(`**Категория:** ${d.role.professionCategoryLabelRu}`);
  }
  if (d.role.specialization) {
    lines.push(`**Специализация:** ${d.role.specialization}`);
  }
  lines.push(`**Уровень мастерства:** ${d.role.professionTier} — _${d.role.professionTierQuality}_`);
  if (d.role.craftingTier?.craftingRu) {
    lines.push(`**Ремесло и последствия:** _${d.role.craftingTier.craftingRu}_`);
  }
  lines.push('');
  lines.push('### Польза для партии');
  lines.push(`**${d.role.utility.name}** — ${d.role.utility.description}`);
  lines.push('');
  lines.push('### Услуги и цены (зм / см)');
  lines.push(
    ...d.role.services.map((s) => {
      const p = s.priceGp ?? '—';
      return `- **${s.work}** — ${p}`;
    }),
  );
  const pr = d.role.pricingRollup;
  if (pr && (pr.totalZm > 0 || pr.totalSm > 0)) {
    lines.push('');
    lines.push(
      `_Ориентир суммы явных чисел в прейскуранте: **${pr.totalZm} зм**, **${pr.totalSm} см** (${pr.noteRu})._`,
    );
  }
  const rp = d.role.repairPricing;
  if (rp?.sampleWeapon && rp?.sampleMagicItem) {
    lines.push('');
    lines.push('### Ремонт и целостность лута (ориентир)');
    lines.push(rp.sampleWeapon.summaryRu);
    lines.push(rp.sampleMagicItem.summaryRu);
  }
  lines.push('');
  lines.push('### Социальная роль по отношению к героям');
  lines.push(`**${d.plot.socialStake.roleLabel}**`);
  lines.push(d.plot.socialStake.explanation);
  lines.push('');
  lines.push('### Отношение к группе (Disposition)');
  lines.push(`**${d.portrayal.disposition.label}**`);
  lines.push(`_Числовой модификатор социальных проверок (ориентир для Мастера): **${d.portrayal.disposition.modifier >= 0 ? '+' : ''}${d.portrayal.disposition.modifier}**_`);
  lines.push('');
  lines.push('### Образ');
  lines.push(d.portrayal.appearance);
  lines.push('');
  if (d.portrayal.craftsmanshipNarrativeHook) {
    lines.push('### Ремесло в жесте');
    lines.push(`_${d.portrayal.craftsmanshipNarrativeHook}_`);
    lines.push('');
  }
  if (d.portrayal.hobbyEclectic) {
    lines.push('### Хобби (контраст с профессией)');
    lines.push(`_${d.portrayal.hobbyEclectic}_`);
    lines.push('');
  }
  if (d.portrayal.whereToFindNow) {
    lines.push('### Где найти прямо сейчас');
    lines.push(d.portrayal.whereToFindNow);
    lines.push('');
  }
  lines.push('### Манера');
  lines.push(d.portrayal.manner);
  lines.push('');
  lines.push('### Первые слова');
  lines.push(`_Настроение реплики: ${d.portrayal.greetingMood}_`);
  lines.push(`> ${d.portrayal.greetingFirstPhrase}`);
  lines.push('');
  lines.push('### Секрет / крючок');
  lines.push(d.plot.secretOrHook);
  lines.push('');
  lines.push('### Карманы');
  lines.push(...d.plot.pockets.map((item) => `- ${item}`));
  lines.push('');
  lines.push('### Предыстория');
  lines.push(d.narrative.backstoryParagraph);
  lines.push('');
  lines.push('---');
  lines.push(`_Сгенерировано: ${d.meta.generatedAt}_`);
  return lines.join('\n');
}

